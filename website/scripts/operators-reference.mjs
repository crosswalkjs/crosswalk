// Writes docs/operators/reference.md from the built-in operators in the built
// core package, so the reference can't drift from the code. Runs before the
// docs build; build the packages first (npm run build in the repo root).
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {builtinCategories, builtinOperators} from '../../packages/core/dist/index.js';

// One line on what each operator does, for those without a description of their own.
const summaries = {
  'text.concat': 'Joins its inputs into one piece of text, in input order.',
  'text.upper': 'The text in capitals.',
  'text.lower': 'The text in lower case.',
  'text.trim': 'The text without spaces at either end.',
  'text.length': 'How many characters the text has.',
  'math.add': 'The sum of its inputs.',
  'math.subtract': 'The first input minus the second.',
  'math.multiply': 'The product of its inputs.',
  'math.divide': 'The first input divided by the second. Dividing by zero is an error.',
  'math.modulo': 'The remainder when the first input is divided by the second.',
  'math.abs': 'The number without its sign.',
  'math.min': 'The smallest of its inputs.',
  'math.max': 'The largest of its inputs.',
  'logic.equal': 'True when the inputs are equal: as numbers if both are numeric, otherwise as text.',
  'logic.notEqual': 'True when the inputs differ.',
  'logic.greaterThan': 'True when the first input is greater than the second.',
  'logic.greaterOrEqual': 'True when the first input is at least the second.',
  'logic.lessThan': 'True when the first input is less than the second.',
  'logic.lessOrEqual': 'True when the first input is at most the second.',
  'logic.and': 'True when every input is true.',
  'logic.or': 'True when any input is true.',
  'logic.not': 'The opposite of its input.',
  'logic.isNumber': 'True when the input is a number, or text holding a plain decimal number such as `"12.5"` (not `"0x10"`).',
  'convert.toNumber': 'Reads the input as a number. Text that isn\'t a plain decimal number is an error.',
  'convert.toText': 'Reads the input as text.',
  'convert.toBoolean': 'Reads `true`, `false`, their text, or a number (0 is false) as true or false.',
  'flow.ifElse': 'The `then` input when the condition is true, otherwise the `else` input.',
  'aggregate.sum': 'Adds up the input across every item.',
  'aggregate.count': 'How many items have a value for the input.',
  'aggregate.average': 'The mean of the input across every item.',
  'aggregate.min': 'The smallest value of the input across every item.',
  'aggregate.max': 'The largest value of the input across every item.',
  'aggregate.join': 'Joins the input from every item into one piece of text.',
};

const inputs = (operator) => {
  const {min, max, labels} = operator.inputs;
  if (labels) return labels.map((label, index) => (index < min ? label : `${label} (optional)`)).join(', ');
  if (max === undefined) return `${min} or more`;
  return min === max ? String(min) : `${min} to ${max}`;
};

const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

let markdown = `---
title: Built-in operators
description: Every operator Crosswalk ships with.
---

{/* Generated by scripts/operators-reference.mjs from @crosswalkjs/core. Edit the operators or that script, not this file. */}

# Built-in operators

Crosswalk ships with ${builtinOperators.length} operators. Every one is included by default; [Your own operators](./custom-operators.md) shows how to choose a subset or add your own.

An operator's **inputs** are filled in the order you link them, and any input can be a constant typed into the inspector instead. When an input has no value, most operators produce nothing too, and the target field is left out. See [How a map runs](../maps/how-maps-run.md).
`;

for (const category of builtinCategories) {
  const operators = builtinOperators.filter((operator) => operator.category === category.id);
  if (operators.length === 0) continue;
  markdown += `\n## ${category.label}\n\n| Operator | Id | Inputs | What it does |\n|---|---|---|---|\n`;
  for (const operator of operators) {
    const what = operator.description ?? summaries[operator.id] ?? '';
    // Glyphs go in code spans: MDX would read one such as `<` as the start of a tag.
    markdown += `| \`${cell(operator.glyph ?? '')}\` ${cell(operator.label)} | \`${operator.id}\` | ${cell(inputs(operator))} | ${cell(what)} |\n`;
  }
  if (category.id === 'aggregate') {
    markdown += `\nAggregate operators take a **scope**: the repeating record they aggregate over, such as \`PhoneCalls[]\`. In the editor, drag the record onto the operator to set it.\n`;
  }
}

const missing = builtinOperators.filter((operator) => !operator.description && !summaries[operator.id]).map((operator) => operator.id);
if (missing.length > 0) throw new Error(`No description for ${missing.join(', ')}. Add one to the operator or to the summaries in this script.`);

writeFileSync(fileURLToPath(new URL('../docs/operators/reference.mdx', import.meta.url)), markdown);
console.log(`Wrote the reference for ${builtinOperators.length} operators.`);
